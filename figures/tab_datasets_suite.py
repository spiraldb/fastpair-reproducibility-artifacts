"""Emit the LaTeX body of tab:datasets from a suite campaign.

    uv run figures/tab_datasets_suite.py                       # rows to stdout
    uv run figures/tab_datasets_suite.py --suite-id paper-20260821

Replaces figures/tab_datasets.py for the fifteen-column corpus. That file reads the OLD ten-column
corpus (dataset ids tpch-sf10, lship) and cannot express this one; it is left in place because the
older figures still cite it.

MEASURED ON THE B300, one chip, as the caption says. Not a mean over chips: the previous generator
averaged mem_ratio across four GPUs because OnPair's dictionary training was unseeded and a
synthetic column's ratio moved per machine. Training is seeded now (20260819, asserted by the
suite's own acceptance), so one chip is reproducible and a mean would only blur it.

DEFINITIONS are figures/suite.py's, which exist so a number means the same thing in the table and
in every figure. The two that are easy to get wrong:

  Len    sample_bytes / (compressed_bytes / 2), the TOKEN-WEIGHTED mean decoded bytes per code.
         Not gpu.dict_mean_len, the unweighted mean over dictionary entries, which runs ~25%
         high and silently overstates the column.
  Ratio  sample_bytes / on_disk_bytes, the AT-REST ratio: string bytes in against the stored
         .vortex file. Not gpu.compressed_bytes, which is the in-memory unpack (exactly 2 B per
         code) and understated OnPair-12 by up to a third. See suite.ratio().

MISSING CELLS PRINT `--`, they do not vanish and they do not raise. A partial campaign is the
normal state while legs are still landing, and a row that quietly disappears is how a reader comes
to believe the corpus is smaller than it is.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import suite as S  # noqa: E402


def fmt_int(v):
    if v is None:
        return "--"
    return f"{v:,}".replace(",", "\\,")


def fmt(v, spec, suffix=""):
    return "--" if v is None else format(v, spec) + suffix


def row(label, ds, col, c12, c16, cf):
    """One table row: OnPair-12 | OnPair-16 | FSST-12.

    FSST-12 has no <=8B column: gpu.frac_le8 is 1.0 on every FSST row by construction, so the
    cell would carry no information."""
    cells = [
        fmt_int(S.tokens(c12)), fmt(S.mean_len(c12), ".1f"),
        fmt(S.frac_le8(c12) * 100 if S.frac_le8(c12) is not None else None, ".0f", "\\%"),
        fmt(S.ratio(c12), ".1f"),
        "",
        fmt_int(S.tokens(c16)), fmt(S.mean_len(c16), ".1f"),
        fmt(S.frac_le8(c16) * 100 if S.frac_le8(c16) is not None else None, ".0f", "\\%"),
        fmt(S.ratio(c16), ".1f"),
        "",
        fmt_int(S.tokens(cf)), fmt(S.mean_len(cf), ".1f"), fmt(S.ratio(cf), ".1f"),
    ]
    return f"{label} & " + " & ".join(cells) + " \\\\"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite-id", default=None)
    ap.add_argument("--chip", default="b300")
    a = ap.parse_args()

    root = S.latest_root(a.suite_id)
    if root is None:
        sys.exit("no results/suite-* directory found")
    c12 = S.cells(root, a.chip, "boost", "onpair")
    c16 = c12
    cf = S.cells(root, a.chip, "boost", "fsst12")

    def pick(store, ds, col, bits):
        return store.get((ds, col, bits))

    missing = []
    out = []
    for group, rows in (("real", S.REAL), ("gen", S.GEN)):
        for label, ds, col in rows:
            r12, r16 = pick(c12, ds, col, 12), pick(c16, ds, col, 16)
            rf = pick(cf, ds, col, 12)
            for name, cell in (("OnPair-12", r12), ("OnPair-16", r16), ("FSST-12", rf)):
                if cell is None:
                    missing.append(f"{ds}/{col} {name}")
            out.append(row(label, ds, col, r12, r16, rf))
        if group == "real":
            out.append("\\midrule")

    print(f"% GENERATED by figures/tab_datasets_suite.py from results/{root.name}/{a.chip}")
    print("% Ratio = sample_bytes/on_disk_bytes (at rest); Len = sample_bytes/(gpu.compressed_bytes/2)")
    print("\n".join(out))
    if missing:
        print(f"\n% INCOMPLETE: {len(missing)} cells absent -> printed as --", file=sys.stderr)
        for m in missing[:10]:
            print(f"%   {m}", file=sys.stderr)
    else:
        print(f"\n% all 15 columns x 3 codecs present", file=sys.stderr)


if __name__ == "__main__":
    main()
